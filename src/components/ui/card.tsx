import * as React from 'react';

import { cn } from '@/lib/utils';

/**
 * Card
 *
 * A matte surface separated by a hairline border, never a shadow
 * (DESIGN_SYSTEM.md §6). The root previously carried `animate-fade-in-up`,
 * so every card on a page slid in on mount — including on re-render after a
 * poll. Entrance animation belongs to the page, not to a container primitive.
 */
const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      data-slot="card"
      className={cn(
        'bg-surface-raised text-fg border-line flex flex-col rounded-lg border',
        className
      )}
      {...props}
    />
  )
);
Card.displayName = 'Card';

